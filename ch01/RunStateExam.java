package ch01;

public class RunStateExam {

	public static void main(String[] args) {
		// 
		int x = 1 ; // x 정수타입의 x변수에 1을 넣는다.
		int y = 2 ; // y 정수타입의 y변수에 2를 넣는다.
		int result = x + y ; // 정수타입의 result 변수의 x변수와 y변수를 더해 넣는다
		
		System.out.println("x+y=" + result); // sysout+ctrl+spacebar
		
		int t = 8 ;
		int v = 12 ;
		int cat = v - t ;
		
		System.out.println("cat=" + cat);
		System.out.println("8=" + cat);
		// Console 창에 결과를 출력한다.

	}

}
