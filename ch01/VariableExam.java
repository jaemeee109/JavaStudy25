package ch01;

public class VariableExam {

	public static void main(String[] args) {
		
		int mach ;
		int distance ;
		mach = 360 ;
		distance = mach / 3 / 4 ;
		
		System.out.print("내 맘대로 계산 = ");
		System.out.println(distance + " m");
		
		double radius ;
		double area ;
		// 실수타입은 소수점이 있다.
		
		radius = 9 ;
		area = radius * radius * 3.14 ;
		
		System.out.print("반지름이 " + radius + "인 ");
		System.out.println("원의 넓이는 = " + area );
				
				

	}

}
