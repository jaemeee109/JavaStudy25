SELECT E.EMPNO, E.ENAME, E.JOB,E.MGR, E.HIREDATE, E.SAL,E.COMM, E.DEPTNO, D.DNAME, D.LOC FROM EMP E JOIN DEPT D ON (E.DEPTNO = D.DEPTNO) WHERE SAL>= 3000 ORDER BY DEPTNO, EMPNO; -- ORDER BY 에 있는 EMPNO는 EMP에서 가져오는 EMPNO가 유일하기 때문에 식별이 가능해서 테이블명을 앞에 붙이지 않음
-- OUTER JOIN ( FROM 테이블1 LEFT(OR RIGHT, OR FULL) OUTER JOIN 테이블2 ON (조건식)
SELECT E1.EMPNO, E1.ENAME, E1.MGR, E2.EMPNO AS MGR_EMPNO, E2.ENAME AS MGR_ENAME FROM EMP E1 LEFT OUTER JOIN EMP E2 ON(E1.MGR = E2.EMPNO) ORDER BY E1.EMPNO;-- 왼쪽 외부 조인
SELECT E1.EMPNO, E1.ENAME, E1.MGR, E2.EMPNO AS MGR_EMPNO, E2.ENAME AS MGR_ENAME FROM EMP E1 RIGHT OUTER JOIN EMP E2 ON(E1.MGR = E2.EMPNO) ORDER BY E1.EMPNO, MGR_EMPNO;-- 오른쪽 외부 조인
SELECT E1.EMPNO, E1.ENAME, E1.MGR, E2.EMPNO AS MGR_EMPNO, E2.ENAME AS MGR_ENAME FROM EMP E1 FULL OUTER JOIN EMP E2 ON(E1.MGR = E2.EMPNO) ORDER BY E1.EMPNO;-- 전체 외부 조인
